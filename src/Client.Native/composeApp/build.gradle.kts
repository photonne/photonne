// The app's own version (component "native" in release-please-config.json),
// independent from the server's <Version> in Directory.Build.props.
val photonneVersion: String =
    rootProject.file("version.txt").takeIf { it.exists() }?.readText()?.trim()?.ifEmpty { null } ?: "0.0.0"
// Oldest server this app works with (see Directory.Build.props).
val photonneMinServerVersion: String = readBuildProp("PhotonneMinServerVersion") ?: "0.0.0"
// Only a prefill for the login wizard. Nothing is baked in unless passed
// explicitly (-PApiBaseUrl=...), except the emulator's host alias for Android
// debug builds — a release must never ship a developer's address.
val apiBaseUrl: String = (findProperty("ApiBaseUrl") as? String).orEmpty()
val androidDebugApiBaseUrl: String = apiBaseUrl.ifEmpty { "http://10.0.2.2:1107" }

// Release signing, from Gradle properties or environment variables (CI
// secrets). Without them the release APK is built unsigned.
fun signingValue(name: String): String? =
    (findProperty(name) as? String ?: System.getenv(name))?.takeIf { it.isNotBlank() }
val releaseKeystore: String? = signingValue("PHOTONNE_KEYSTORE_FILE")

val generatedCommonDir = layout.buildDirectory.dir("generated/photonne/commonMain/kotlin")
val writePhotonneVersion = tasks.register("writePhotonneVersion") {
    val outDir = generatedCommonDir
    val versionValue = photonneVersion
    val minServerValue = photonneMinServerVersion
    inputs.property("photonneVersion", versionValue)
    inputs.property("photonneMinServerVersion", minServerValue)
    outputs.dir(outDir)
    doLast {
        val pkgDir = outDir.get().asFile.resolve("com/photonne/app")
        pkgDir.mkdirs()
        pkgDir.resolve("PhotonneVersion.kt").writeText(
            """
            package com.photonne.app

            /** Generated by Gradle from src/Client.Native/version.txt. */
            const val PhotonneVersion: String = "$versionValue"

            /** Oldest server version this app works with (Directory.Build.props). */
            const val PhotonneMinServerVersion: String = "$minServerValue"
            """.trimIndent() + "\n"
        )
    }
}

